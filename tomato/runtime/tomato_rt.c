/* The shortest text that reads back as the same double, laid out like the interpreter prints it: fixed notation
 * when the exponent is from -4 to 15 (with ".0" kept on whole numbers), otherwise d.ddde+XX. */
static int format_f64(double v, char *out) {
    char buf[64], digits[32];
    int len = 0;
    if (isnan(v)) return sprintf(out, "nan");
    if (isinf(v)) return sprintf(out, v < 0 ? "-inf" : "inf");
    int prec;
    for (prec = 0; prec < 17; prec++) {
        snprintf(buf, sizeof buf, "%.*e", prec, v);
        if (strtod(buf, NULL) == v) break;
    }
    char *e = strchr(buf, 'e');
    int exp10 = atoi(e + 1);
    int neg = buf[0] == '-';
    char *m = buf + neg;
    int n = 0;
    for (char *q = m; q < e; q++) if (*q != '.') digits[n++] = *q;
    digits[n] = '\0';
    if (neg) out[len++] = '-';
    if (exp10 >= -4 && exp10 < 16) {
        if (exp10 < 0) {
            len += sprintf(out + len, "0.");
            for (int k = 0; k < -exp10 - 1; k++) out[len++] = '0';
            len += sprintf(out + len, "%s", digits);
        } else if (n <= exp10 + 1) {
            len += sprintf(out + len, "%s", digits);
            for (int k = 0; k < exp10 + 1 - n; k++) out[len++] = '0';
            len += sprintf(out + len, ".0");
        } else {
            len += sprintf(out + len, "%.*s.%s", exp10 + 1, digits, digits + exp10 + 1);
        }
    } else {
        out[len++] = digits[0];
        if (n > 1) len += sprintf(out + len, ".%s", digits + 1);
        len += sprintf(out + len, "e%c%02d", exp10 < 0 ? '-' : '+', abs(exp10));
    }
    out[len] = '\0';
    return len;
}

void tomato_print_f64(double v) {
    char out[96];
    format_f64(v, out);
    fputs(out, stdout);
}

static void bad_input(int position, const char *what, const char *text) {
    char msg[256];
    snprintf(msg, sizeof msg, "input %d must be %s, found '%s'", position, what, text);
    tomato_fail(msg);
}

void tomato_usage(int expected, int got) {
    char msg[128];
    snprintf(msg, sizeof msg, "the entry point takes %d input(s), got %d", expected, got);
    tomato_fail(msg);
}

int64_t tomato_parse_i64(const char *text, int position) {
    char *end;
    errno = 0;
    long long v = strtoll(text, &end, 10);
    if (*text == '\0' || *end != '\0' || errno != 0 || isspace((unsigned char)*text))
        bad_input(position, "a whole number", text);
    return v;
}

uint64_t tomato_parse_u64(const char *text, int position) {
    char *end;
    errno = 0;
    if (*text == '-' || *text == '+' || isspace((unsigned char)*text)) bad_input(position, "a whole number", text);
    unsigned long long v = strtoull(text, &end, 10);
    if (*text == '\0' || *end != '\0' || errno != 0) bad_input(position, "a whole number", text);
    return v;
}

double tomato_parse_f64(const char *text, int position) {
    char *end;
    double v = strtod(text, &end);
    if (*text == '\0' || *end != '\0' || isnan(v) || isinf(v)) bad_input(position, "a finite number", text);
    return v;
}

int tomato_parse_bool(const char *text, int position) {
    if (!strcmp(text, "true") || !strcmp(text, "True")) return 1;
    if (!strcmp(text, "false") || !strcmp(text, "False")) return 0;
    bad_input(position, "true or false", text);
    return 0;
}

/* Checks that a parsed integer fits an N-bit type (N < 64) before the generated code narrows it. */
void tomato_fit_signed(int64_t v, int bits, int position) {
    if (v < -((int64_t)1 << (bits - 1)) || v >= ((int64_t)1 << (bits - 1))) {
        char msg[128];
        snprintf(msg, sizeof msg, "input %d (%lld) does not fit int[length=%d]", position, (long long)v, bits);
        tomato_fail(msg);
    }
}

void tomato_fit_unsigned(uint64_t v, int bits, int position) {
    if (v >= ((uint64_t)1 << bits)) {
        char msg[128];
        snprintf(msg, sizeof msg, "input %d (%llu) does not fit uint[length=%d]", position, (unsigned long long)v, bits);
        tomato_fail(msg);
    }
}


/* ---- allocation and reference counting ---- */
void *tomato_alloc(int64_t size, int64_t type) {
    Hdr *h = calloc(1, (size_t)size);
    if (!h) tomato_fail("out of memory");
    h->rc = 1;
    h->type = type;
    live_objects++;
    return h;
}

void tomato_retain(void *p) {
    if (p && ((Hdr *)p)->rc > 0) ((Hdr *)p)->rc++;   /* an immortal object (rc < 0) is never counted */
}

void tomato_release(void *p) {
    if (!p) return;
    Hdr *h = p;
    if (h->rc <= 0) return;                 /* immortal (negative) or already dead */
    if (--h->rc == 0) destroy_object(h);
    else possible_root(h);                  /* still referenced: it might be the last outside reference of a cycle */
}

/* Debug mode: objects still alive at exit were never released, usually a reference cycle (D29c). */
extern int32_t tomato_exc_seen;   /* set when any error was raised during the run */
extern const char *tomato_class_names[];

void tomato_collect_cycles(void);

void tomato_leak_check(void) {
    tomato_collect_cycles();     /* cycles are freed automatically (D29d), so only true leaks are left to report */
    /* After an error was raised, temporaries held in the middle of an expression can be dropped without being
     * released, so the check would report false leaks: it stays quiet then. */
    if (live_objects != 0 && !tomato_exc_seen) {
        fflush(stdout);
        fprintf(stderr, "warning: %lld object(s) were never freed (a reference cycle or a missing release)\n",
                (long long)live_objects);
    }
}

/* ---- strings: {header, byte length, character length, UTF-8 bytes}; type code 1 ---- */
typedef struct { Hdr h; int64_t bytes; int64_t chars; char data[]; } Str;

static int64_t count_chars(const char *s, int64_t n) {
    int64_t k = 0;
    for (int64_t i = 0; i < n; i++) if (((unsigned char)s[i] & 0xC0) != 0x80) k++;
    return k;
}

static Str *str_new(const char *bytes, int64_t n) {
    Str *s = tomato_alloc((int64_t)sizeof(Str) + n + 1, 1);
    memcpy(s->data, bytes, (size_t)n);
    s->bytes = n;
    s->chars = count_chars(bytes, n);
    return s;
}

void *tomato_str_from_cstr(const char *c) { return str_new(c, (int64_t)strlen(c)); }

void *tomato_str_concat(void *a, void *b) {
    Str *x = a, *y = b;
    Str *s = tomato_alloc((int64_t)sizeof(Str) + x->bytes + y->bytes + 1, 1);
    memcpy(s->data, x->data, (size_t)x->bytes);
    memcpy(s->data + x->bytes, y->data, (size_t)y->bytes);
    s->bytes = x->bytes + y->bytes;
    s->chars = x->chars + y->chars;
    return s;
}

int64_t tomato_str_len(void *s) { return ((Str *)s)->chars; }

/* Compares by bytes, which for UTF-8 is the same as comparing code points (D17b). Returns <0, 0 or >0. */
int tomato_str_cmp(void *a, void *b) {
    Str *x = a, *y = b;
    int64_t n = x->bytes < y->bytes ? x->bytes : y->bytes;
    int r = memcmp(x->data, y->data, (size_t)n);
    if (r) return r;
    return x->bytes < y->bytes ? -1 : x->bytes > y->bytes ? 1 : 0;
}

/* The byte offset of character number i (0 <= i <= chars). The scan is linear; a chunked index is later work (D17c). */
static int64_t char_offset(Str *s, int64_t i) {
    int64_t seen = 0;
    for (int64_t k = 0; k < s->bytes; k++) {
        if (((unsigned char)s->data[k] & 0xC0) != 0x80) {
            if (seen == i) return k;
            seen++;
        }
    }
    return s->bytes;
}

void *tomato_str_index(void *a, int64_t i) {
    Str *s = a;
    if (i < 0 || i >= s->chars) return NULL;      /* the compiled code raises the error */
    int64_t from = char_offset(s, i), to = char_offset(s, i + 1);
    return str_new(s->data + from, to - from);
}

void *tomato_str_slice(void *a, int64_t lo, int64_t hi) {
    Str *s = a;
    if (lo < 0 || lo > hi || hi > s->chars) return NULL;
    int64_t from = char_offset(s, lo), to = char_offset(s, hi);
    return str_new(s->data + from, to - from);
}

/* ---- text searching and splitting (bootstrap, D38a) ---- */
void *tomato_list_new(int64_t type);
void *tomato_list_push(void *l, int64_t elem_size);
static int64_t byte_to_char(Str *s, int64_t byte) {
    int64_t seen = 0;
    for (int64_t k = 0; k < byte; k++)
        if (((unsigned char)s->data[k] & 0xC0) != 0x80) seen++;
    return seen;
}

static int64_t find_bytes(Str *h, Str *n, int64_t from) {
    if (n->bytes == 0) return from <= h->bytes ? from : -1;
    for (int64_t i = from; i + n->bytes <= h->bytes; i++)
        if (memcmp(h->data + i, n->data, (size_t)n->bytes) == 0) return i;
    return -1;
}

/* The character index of the first match, or -1. */
int64_t tomato_str_find(void *hay, void *needle) {
    int64_t at = find_bytes(hay, needle, 0);
    return at < 0 ? -1 : byte_to_char(hay, at);
}

int tomato_str_startswith(void *hay, void *p) {
    Str *h = hay, *x = p;
    return x->bytes <= h->bytes && memcmp(h->data, x->data, (size_t)x->bytes) == 0;
}

int tomato_str_endswith(void *hay, void *p) {
    Str *h = hay, *x = p;
    return x->bytes <= h->bytes && memcmp(h->data + h->bytes - x->bytes, x->data, (size_t)x->bytes) == 0;
}

/* Every non-overlapping `a` replaced by `b`; the compiler rejects an empty `a`. */
void *tomato_str_replace(void *src, void *a, void *b) {
    Str *s = src, *x = a, *y = b;
    int64_t cap = s->bytes + 1, len = 0, at = 0;
    char *out = malloc((size_t)cap);
    if (!out) tomato_fail("out of memory");
    while (at <= s->bytes) {
        int64_t hit = find_bytes(s, x, at);
        int64_t upto = hit < 0 ? s->bytes : hit;
        int64_t need = len + (upto - at) + (hit < 0 ? 0 : y->bytes) + 1;
        if (need > cap) { cap = need * 2; out = realloc(out, (size_t)cap); if (!out) tomato_fail("out of memory"); }
        memcpy(out + len, s->data + at, (size_t)(upto - at));
        len += upto - at;
        if (hit < 0) break;
        memcpy(out + len, y->data, (size_t)y->bytes);
        len += y->bytes;
        at = hit + x->bytes;
    }
    void *r = str_new(out, len);
    free(out);
    return r;
}

/* A new list of the pieces between each `sep`; the compiler rejects an empty `sep`. */
void *tomato_str_split(void *src, void *sep, int64_t list_type, int64_t elem_size) {
    Str *s = src, *x = sep;
    void *l = tomato_list_new(list_type);
    int64_t at = 0;
    for (;;) {
        int64_t hit = find_bytes(s, x, at);
        int64_t upto = hit < 0 ? s->bytes : hit;
        void *piece = str_new(s->data + at, upto - at);
        void **slot = tomato_list_push(l, elem_size);
        *slot = piece;
        if (hit < 0) break;
        at = hit + x->bytes;
    }
    return l;
}

/* ---- files (bootstrap, D38a): a FILE* the program opens and closes itself ---- */
void *tomato_file_open(void *path, void *mode) {
    return fopen(((Str *)path)->data, ((Str *)mode)->data);
}

void *tomato_file_read(void *f) {
    char buf[4096];
    int64_t cap = 4096, len = 0;
    char *out = malloc((size_t)cap);
    size_t got;
    if (!out) tomato_fail("out of memory");
    while ((got = fread(buf, 1, sizeof buf, f)) > 0) {
        if (len + (int64_t)got > cap) { cap = (len + (int64_t)got) * 2; out = realloc(out, (size_t)cap); if (!out) tomato_fail("out of memory"); }
        memcpy(out + len, buf, got);
        len += (int64_t)got;
    }
    void *r = str_new(out, len);
    free(out);
    return r;
}

void tomato_file_write(void *f, void *s) { fwrite(((Str *)s)->data, 1, (size_t)((Str *)s)->bytes, f); }
void tomato_file_close(void *f) { fclose(f); }

void tomato_print_strobj(void *s) { fwrite(((Str *)s)->data, 1, (size_t)((Str *)s)->bytes, stdout); }

void *tomato_str_from_i64(int64_t v) { char b[32]; int n = snprintf(b, sizeof b, "%lld", (long long)v); return str_new(b, n); }
void *tomato_str_from_u64(uint64_t v) { char b[32]; int n = snprintf(b, sizeof b, "%llu", (unsigned long long)v); return str_new(b, n); }
void *tomato_str_from_f64(double v) { char b[96]; int n = format_f64(v, b); return str_new(b, n); }
void *tomato_str_from_bool(int v) { return tomato_str_from_cstr(v ? "True" : "False"); }

/* ---- lists: {header, length, capacity, data}; the element type is known to the compiler ---- */
typedef struct { Hdr h; int64_t len; int64_t cap; char *data; } List;

void *tomato_list_new(int64_t type) { return tomato_alloc((int64_t)sizeof(List), type); }

/* Makes room for one more element and returns the address of its slot; the caller stores the element. */
void *tomato_list_push(void *l, int64_t elem_size) {
    List *x = l;
    if (x->len == x->cap) {
        x->cap = x->cap ? x->cap * 2 : 4;
        x->data = realloc(x->data, (size_t)(x->cap * elem_size));
        if (!x->data) tomato_fail("out of memory");
    }
    return x->data + (x->len++) * elem_size;
}

/* The items of a list[str] joined with `sep` between them. */
void *tomato_str_join(void *sep, void *list) {
    Str *x = sep;
    List *l = list;
    int64_t total = 0;
    for (int64_t i = 0; i < l->len; i++) total += ((Str **)l->data)[i]->bytes + (i ? x->bytes : 0);
    char *out = malloc((size_t)total + 1);
    if (!out) tomato_fail("out of memory");
    int64_t at = 0;
    for (int64_t i = 0; i < l->len; i++) {
        if (i) { memcpy(out + at, x->data, (size_t)x->bytes); at += x->bytes; }
        Str *piece = ((Str **)l->data)[i];
        memcpy(out + at, piece->data, (size_t)piece->bytes);
        at += piece->bytes;
    }
    void *r = str_new(out, total);
    free(out);
    return r;
}


void tomato_list_free_data(void *l) { free(((List *)l)->data); }

/* Is an object of class `code` an instance of the class `target` (the class itself or a descendant)? (D12az) */
int tomato_is_subclass(int64_t code, int64_t target) {
    while (code) {
        if (code == target) return 1;
        code = tomato_parents[code];
    }
    return 0;
}

/* ---- dicts and sets: insertion-ordered hash tables (D20b, D20c) ----
 * Entries live in an array {live, key word, hash, value bytes}; an index of positions gives expected O(1) lookup.
 * A key word is the integer itself (ints and bools) or a string pointer; key_kind 0 is an integer, 1 a string.
 * A set is a dict with no values. */
typedef struct {
    Hdr h;
    int64_t count, used, cap, index_cap;
    int32_t *index;
    char *entries;
    int64_t val_size, stride;
    int key_kind;
} Dict;

#define ENTRY(d, i) ((d)->entries + (int64_t)(i) * (d)->stride)
#define E_LIVE(e) (*(int64_t *)(e))
#define E_KEY(e) (*(int64_t *)((e) + 8))
#define E_HASH(e) (*(int64_t *)((e) + 16))
#define E_VAL(e) ((e) + 24)

void *tomato_dict_new(int64_t type, int64_t val_size, int key_kind) {
    Dict *d = tomato_alloc((int64_t)sizeof(Dict), type);
    d->val_size = val_size;
    d->stride = 24 + ((val_size + 7) / 8) * 8;
    d->key_kind = key_kind;
    return d;
}

static int64_t hash_key(int kind, int64_t key) {
    uint64_t h;
    if (kind == 1) {
        Str *s = (Str *)key;
        h = 1469598103934665603ULL;
        for (int64_t i = 0; i < s->bytes; i++) { h ^= (unsigned char)s->data[i]; h *= 1099511628211ULL; }
    } else {
        h = (uint64_t)key + 0x9e3779b97f4a7c15ULL;
        h = (h ^ (h >> 30)) * 0xbf58476d1ce4e5b9ULL;
        h = (h ^ (h >> 27)) * 0x94d049bb133111ebULL;
        h ^= h >> 31;
    }
    return (int64_t)(h & 0x7fffffffffffffffULL);
}

static int key_eq(int kind, int64_t a, int64_t b) {
    if (kind == 1) return tomato_str_cmp((void *)a, (void *)b) == 0;
    return a == b;
}

static void rebuild_index(Dict *d, int64_t index_cap) {
    free(d->index);
    d->index_cap = index_cap;
    d->index = malloc((size_t)index_cap * sizeof(int32_t));
    if (!d->index) tomato_fail("out of memory");
    for (int64_t i = 0; i < index_cap; i++) d->index[i] = -1;
    for (int64_t i = 0; i < d->used; i++) {
        char *e = ENTRY(d, i);
        if (!E_LIVE(e)) continue;
        int64_t pos = E_HASH(e) & (index_cap - 1);
        while (d->index[pos] != -1) pos = (pos + 1) & (index_cap - 1);
        d->index[pos] = (int32_t)i;
    }
}

static char *dict_find_entry(Dict *d, int64_t key, int64_t hash) {
    if (!d->index_cap) return NULL;
    int64_t pos = hash & (d->index_cap - 1);
    for (;;) {
        int32_t i = d->index[pos];
        if (i == -1) return NULL;
        if (i >= 0) {
            char *e = ENTRY(d, i);
            if (E_LIVE(e) && E_HASH(e) == hash && key_eq(d->key_kind, E_KEY(e), key)) return e;
        }
        pos = (pos + 1) & (d->index_cap - 1);
    }
}

/* The address of the value for `key`, or NULL when the key is missing. For a set it is a valid address too. */
void *tomato_dict_find(void *dp, int64_t key) {
    Dict *d = dp;
    char *e = dict_find_entry(d, key, hash_key(d->key_kind, key));
    return e ? E_VAL(e) : NULL;
}

/* Adds `key` if it is missing and returns the address of its (zeroed) value; returns NULL if it was already there
 * and `only_new` is set. A string key is retained by the table. */
void *tomato_dict_insert(void *dp, int64_t key, int only_new) {
    Dict *d = dp;
    int64_t hash = hash_key(d->key_kind, key);
    char *e = dict_find_entry(d, key, hash);
    if (e) return only_new ? NULL : E_VAL(e);
    int compacted = 0;
    if (d->used == d->cap) {
        int64_t cap = d->cap ? d->cap * 2 : 4;
        if (d->count < d->used * 3 / 4) {            /* many deleted entries: compact in place instead of growing */
            int64_t w = 0;
            for (int64_t i = 0; i < d->used; i++) {
                char *src = ENTRY(d, i);
                if (!E_LIVE(src)) continue;
                if (w != i) memcpy(ENTRY(d, w), src, (size_t)d->stride);
                w++;
            }
            memset(ENTRY(d, w), 0, (size_t)((d->used - w) * d->stride));
            d->used = w;
            cap = d->cap;
            compacted = 1;
        } else {
            d->entries = realloc(d->entries, (size_t)(cap * d->stride));
            if (!d->entries) tomato_fail("out of memory");
            d->cap = cap;
        }
    }
    if (d->index_cap < 2 * (d->used + 1)) {
        int64_t ic = d->index_cap ? d->index_cap : 8;
        while (ic < 2 * (d->used + 1)) ic *= 2;
        rebuild_index(d, ic);
    } else if (compacted) {
        rebuild_index(d, d->index_cap);
    }
    e = ENTRY(d, d->used);
    memset(e, 0, (size_t)d->stride);
    E_LIVE(e) = 1;
    E_KEY(e) = key;
    E_HASH(e) = hash;
    if (d->key_kind == 1) tomato_retain((void *)key);
    int64_t pos = hash & (d->index_cap - 1);
    while (d->index[pos] >= 0) pos = (pos + 1) & (d->index_cap - 1);
    d->index[pos] = (int32_t)d->used;
    d->used++;
    d->count++;
    return E_VAL(e);
}

/* Removes `key`; the compiled code has already released its value. Returns 0 when the key was not there. */
int tomato_dict_delete(void *dp, int64_t key) {
    Dict *d = dp;
    int64_t hash = hash_key(d->key_kind, key);
    char *e = dict_find_entry(d, key, hash);
    if (!e) return 0;
    if (d->key_kind == 1) tomato_release((void *)E_KEY(e));
    E_LIVE(e) = 0;
    memset(E_VAL(e), 0, (size_t)(d->stride - 24));
    d->count--;
    int64_t pos = hash & (d->index_cap - 1);
    for (;;) {                                        /* mark the index slot deleted */
        int32_t i = d->index[pos];
        if (i >= 0 && ENTRY(d, i) == e) { d->index[pos] = -2; break; }
        pos = (pos + 1) & (d->index_cap - 1);
    }
    return 1;
}

/* A new list holding the keys (or values) in insertion order; a heap key or value is retained for the list. */
void *tomato_dict_keys(void *dp, int64_t list_type, int64_t elem_size) {
    Dict *d = dp;
    void *l = tomato_list_new(list_type);
    for (int64_t i = 0; i < d->used; i++) {
        char *e = ENTRY(d, i);
        if (!E_LIVE(e)) continue;
        void *slot = tomato_list_push(l, elem_size);
        memcpy(slot, &E_KEY(e), (size_t)elem_size);
        if (d->key_kind == 1) tomato_retain((void *)E_KEY(e));
    }
    return l;
}

void *tomato_dict_values(void *dp, int64_t list_type, int64_t elem_size, int val_rc) {
    Dict *d = dp;
    void *l = tomato_list_new(list_type);
    for (int64_t i = 0; i < d->used; i++) {
        char *e = ENTRY(d, i);
        if (!E_LIVE(e)) continue;
        void *slot = tomato_list_push(l, elem_size);
        memcpy(slot, E_VAL(e), (size_t)elem_size);
        if (val_rc) tomato_retain(*(void **)E_VAL(e));
    }
    return l;
}

void tomato_dict_destroy(void *dp, int key_rc, int val_rc) {
    Dict *d = dp;
    for (int64_t i = 0; i < d->used; i++) {
        char *e = ENTRY(d, i);
        if (!E_LIVE(e)) continue;
        if (key_rc) tomato_release((void *)E_KEY(e));
        if (val_rc) tomato_release(*(void **)E_VAL(e));
    }
    free(d->entries);
    free(d->index);
}

int tomato_str_contains(void *hay, void *needle) {
    Str *h = hay, *n = needle;
    if (n->bytes == 0) return 1;
    if (n->bytes > h->bytes) return 0;
    for (int64_t i = 0; i + n->bytes <= h->bytes; i++)
        if (memcmp(h->data + i, n->data, (size_t)n->bytes) == 0) return 1;
    return 0;
}

/* An error nobody caught reached the entry point (D22a). `runtime` is 1 for a failure the language itself raised,
 * whose message is already in the current error mode's form; mode is 1 debug, 2 normal, 3 release (D34a). */
void tomato_report_uncaught(void *obj, int line, int runtime, int mode) {
    fflush(stdout);
    Str *msg = *(Str **)((char *)obj + 16);
    if (mode == 1) {
        if (runtime) fprintf(stderr, "error: %.*s\n", (int)msg->bytes, msg->data);
        else fprintf(stderr, "error: line %d: uncaught error %s: %.*s\n", line, tomato_class_names[((Hdr *)obj)->type & TYPE_MASK],
                     (int)msg->bytes, msg->data);
    } else if (mode == 2) {
        if (runtime) fprintf(stderr, "error %.*s\n", (int)msg->bytes, msg->data);
        else fprintf(stderr, "error E11:%d\n", line);
    }
    exit(1);
}

/* ---- freeing and the cycle collector (D29a, D29d) ----
 * An object is freed when its count reaches 0. Counting alone never frees a cycle, so a synchronous cycle
 * collector (Bacon and Rajan) runs too: an object whose count drops but stays above 0 becomes a possible root;
 * once enough roots pile up, everything reachable from them is traced, counts that come from inside the traced
 * graph are subtracted, and whatever is left with no outside reference is garbage. */
typedef void (*Visit)(Hdr *child);

static void each_child(Hdr *h, Visit f) {
    int64_t code = tcode(h);
    int32_t kind = tomato_kinds[code];
    switch (kind & 15) {
    case 1: {
        for (const int32_t *o = tomato_offsets[code]; *o >= 0; o++) {
            Hdr *c = *(Hdr **)((char *)h + *o);
            if (c) f(c);
        }
        break;
    }
    case 2:
        if (kind & 256) {
            List *l = (List *)h;
            for (int64_t i = 0; i < l->len; i++) {
                Hdr *c = ((Hdr **)l->data)[i];
                if (c) f(c);
            }
        }
        break;
    case 3: {
        Dict *d = (Dict *)h;
        for (int64_t i = 0; i < d->used; i++) {
            char *e = ENTRY(d, i);
            if (!E_LIVE(e)) continue;
            if ((kind & 256) && d->key_kind == 1 && E_KEY(e)) f((Hdr *)E_KEY(e));
            if (kind & 512) { Hdr *c = *(Hdr **)E_VAL(e); if (c) f(c); }
        }
        break;
    }
    default:
        break;
    }
}

static void release_visit(Hdr *c) { tomato_release(c); }

static void free_internals(Hdr *h) {
    int32_t kind = tomato_kinds[tcode(h)] & 15;
    if (kind == 2) { List *l = (List *)h; free(l->data); l->data = NULL; }
    else if (kind == 3) { Dict *d = (Dict *)h; free(d->entries); free(d->index); d->entries = NULL; d->index = NULL; d->used = 0; }
}

/* Objects whose count reached 0 while another is being destroyed wait here, so a long chain does not recurse. */
static Hdr **pending;
static int64_t pending_n, pending_cap;
static int destroying;

static void destroy_one(Hdr *h) {
    each_child(h, release_visit);
    free_internals(h);
    if (h->type & F_BUFFERED) { h->type |= F_DEAD; return; }   /* the collector still points at it: freed there */
    free(h);
    live_objects--;
}

static void destroy_object(Hdr *h) {
    if (destroying) {
        if (pending_n == pending_cap) {
            pending_cap = pending_cap ? pending_cap * 2 : 64;
            pending = realloc(pending, (size_t)pending_cap * sizeof(Hdr *));
            if (!pending) tomato_fail("out of memory");
        }
        pending[pending_n++] = h;
        return;
    }
    destroying = 1;
    destroy_one(h);
    while (pending_n) destroy_one(pending[--pending_n]);
    destroying = 0;
}

static Hdr **roots;
static int64_t roots_n, roots_cap;
static int64_t gc_threshold = 10000;
static int collecting;
static int64_t gc_freed, gc_runs;

static Hdr **stack;
static int64_t stack_n, stack_cap;
static void spush(Hdr *h) {
    if (stack_n == stack_cap) {
        stack_cap = stack_cap ? stack_cap * 2 : 256;
        stack = realloc(stack, (size_t)stack_cap * sizeof(Hdr *));
        if (!stack) tomato_fail("out of memory");
    }
    stack[stack_n++] = h;
}

static Hdr **garbage;
static int64_t garbage_n, garbage_cap;

static void mg_visit(Hdr *c) { if (c->rc > 0) { c->rc--; spush(c); } }
static void mark_gray(Hdr *s) {
    spush(s);
    while (stack_n) {
        Hdr *h = stack[--stack_n];
        if (hcolor(h) == GRAY) continue;
        set_color(h, GRAY);
        each_child(h, mg_visit);
    }
}

static void sb_visit(Hdr *c) { if (c->rc >= 0) { c->rc++; if (hcolor(c) != BLACK) spush(c); } }
static void scan_black(Hdr *s) {
    set_color(s, BLACK);
    each_child(s, sb_visit);
    while (stack_n) {
        Hdr *h = stack[--stack_n];
        if (hcolor(h) == BLACK) continue;
        set_color(h, BLACK);
        each_child(h, sb_visit);
    }
}

static void scan_visit(Hdr *c) { spush(c); }
static void scan(Hdr *s) {
    spush(s);
    while (stack_n) {
        Hdr *h = stack[--stack_n];
        if (hcolor(h) != GRAY) continue;
        if (h->rc > 0) {
            scan_black(h);
        } else {
            set_color(h, WHITE);
            each_child(h, scan_visit);
        }
    }
}

static void cw_visit(Hdr *c) { spush(c); }
static void collect_white(Hdr *s) {
    spush(s);
    while (stack_n) {
        Hdr *h = stack[--stack_n];
        if (hcolor(h) != WHITE || (h->type & F_BUFFERED)) continue;
        set_color(h, BLACK);
        each_child(h, cw_visit);
        if (garbage_n == garbage_cap) {
            garbage_cap = garbage_cap ? garbage_cap * 2 : 256;
            garbage = realloc(garbage, (size_t)garbage_cap * sizeof(Hdr *));
            if (!garbage) tomato_fail("out of memory");
        }
        garbage[garbage_n++] = h;
    }
}

void tomato_collect_cycles(void) {
    if (collecting) return;
    collecting = 1;
    gc_runs++;
    int64_t keep = 0;
    for (int64_t i = 0; i < roots_n; i++) {          /* mark: subtract the counts that come from inside the graph */
        Hdr *s = roots[i];
        if (hcolor(s) == PURPLE && s->rc > 0) {
            mark_gray(s);
            roots[keep++] = s;
        } else {
            s->type &= ~F_BUFFERED;
            if (s->rc == 0 && (s->type & F_DEAD)) { free(s); live_objects--; }
        }
    }
    roots_n = keep;
    for (int64_t i = 0; i < roots_n; i++) scan(roots[i]);      /* scan: restore what is still reachable from outside */
    for (int64_t i = 0; i < roots_n; i++) roots[i]->type &= ~F_BUFFERED;
    garbage_n = 0;
    for (int64_t i = 0; i < roots_n; i++) collect_white(roots[i]);   /* collect: what is left white is a cycle */
    for (int64_t i = 0; i < garbage_n; i++) {
        free_internals(garbage[i]);
        free(garbage[i]);
        live_objects--;
        gc_freed++;
    }
    roots_n = 0;
    gc_threshold = 10000;
    collecting = 0;
    if (getenv("TOMATO_GC_STATS") && gc_freed) fprintf(stderr, "gc: %lld object(s) freed in cycles\n", (long long)gc_freed);
}

static void possible_root(Hdr *h) {
    if ((tomato_kinds[tcode(h)] & 15) == 0) return;      /* strings hold no references, so they are never in a cycle */
    if (hcolor(h) != PURPLE) {
        set_color(h, PURPLE);
        if (!(h->type & F_BUFFERED)) {
            h->type |= F_BUFFERED;
            if (roots_n == roots_cap) {
                roots_cap = roots_cap ? roots_cap * 2 : 1024;
                roots = realloc(roots, (size_t)roots_cap * sizeof(Hdr *));
                if (!roots) tomato_fail("out of memory");
            }
            roots[roots_n++] = h;
        }
    }
    if (roots_n >= gc_threshold && !collecting) tomato_collect_cycles();
}

/* Equality where either side may be None (D23b): None equals only None. */
int tomato_str_eq_opt(void *a, void *b) {
    if (!a || !b) return a == b;
    return tomato_str_cmp(a, b) == 0;
}
