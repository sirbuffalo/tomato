/* The C runtime that compiled Tomato programs link against (P36, P39). It prints values the way the interpreter
 * does, reads the entry point's command-line inputs, stops the program with an error message, and manages heap
 * objects by reference counting (D29a). Every heap object starts with a header {reference count, type code}
 * (D35a); the type code indexes compiler-generated tables that describe the object's fields. A negative count
 * marks an immortal object, such as a string literal. A cycle collector frees reference cycles (D29d), and debug
 * mode reports objects that were never freed (D29c). */
#include <ctype.h>
#include <errno.h>
#include <math.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

typedef struct { int64_t rc; int64_t type; } Hdr;

/* Generated by the compiler, indexed by type code: what an object's fields hold, so the runtime can free it and
 * trace it without per-type code. kind: 0 leaf (a string), 1 class, 2 list, 3 dict or set; bit 8 says list
 * elements or dict keys are heap values, bit 9 that dict values are. For a class, tomato_offsets[type] lists the
 * byte offsets of its heap-valued fields, ended by -1. */
extern const int32_t tomato_kinds[];
extern const int32_t *const tomato_offsets[];
extern int64_t tomato_parents[];  /* generated: the type code of each class's parent, or 0 */
static int64_t live_objects = 0;

/* The type word also carries the cycle collector's state in its upper bits (the type code is the low 32 bits). */
#define TYPE_MASK 0xFFFFFFFFLL
#define F_BUFFERED (1LL << 35)   /* in the collector's list of possible cycle roots */
#define F_DEAD (1LL << 36)       /* reference count reached 0 while buffered: freed by the collector */
enum { BLACK = 0, GRAY = 1, WHITE = 2, PURPLE = 3 };
static int hcolor(Hdr *h) { return (int)((h->type >> 32) & 3); }
static void set_color(Hdr *h, int col) { h->type = (h->type & ~(3LL << 32)) | ((int64_t)col << 32); }
static int64_t tcode(Hdr *h) { return h->type & TYPE_MASK; }

static void possible_root(Hdr *h);
static void destroy_object(Hdr *h);

void tomato_fail(const char *message) {
    fflush(stdout);
    fprintf(stderr, "error: %s\n", message);
    exit(1);
}

/* Normal mode (D34a): a short code that `tomato explain` decodes with the source. Printed as E<kind>:<line>. */
void tomato_fail_code(int kind, int line) {
    fflush(stdout);
    fprintf(stderr, "error E%02d:%d\n", kind, line);
    exit(1);
}

/* Release mode (D34a): no readable error. */
void tomato_trap(void) {
    fflush(stdout);
    exit(1);
}

