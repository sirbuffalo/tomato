/* The shortest text that reads back as the same double, laid out like the interpreter prints it: fixed notation
 * when the exponent is from -4 to 15 (with ".0" kept on whole numbers), otherwise d.ddde+XX. */
static int format_f64(double v, char *out) {
    char buf[64], digits[32];
    int len = 0;
    if (isnan(v)) return sprintf(out, "nan");
    if (isinf(v)) return sprintf(out, v < 0 ? "-inf" : "inf");
    int prec;
    for (prec = 0; prec < 17; prec++) {
        snprintf(buf, sizeof buf, "%.*e", prec, v);
        if (strtod(buf, NULL) == v) break;
    }
    char *e = strchr(buf, 'e');
    int exp10 = atoi(e + 1);
    int neg = buf[0] == '-';
    char *m = buf + neg;
    int n = 0;
    for (char *q = m; q < e; q++) if (*q != '.') digits[n++] = *q;
    digits[n] = '\0';
    if (neg) out[len++] = '-';
    if (exp10 >= -4 && exp10 < 16) {
        if (exp10 < 0) {
            len += sprintf(out + len, "0.");
            for (int k = 0; k < -exp10 - 1; k++) out[len++] = '0';
            len += sprintf(out + len, "%s", digits);
        } else if (n <= exp10 + 1) {
            len += sprintf(out + len, "%s", digits);
            for (int k = 0; k < exp10 + 1 - n; k++) out[len++] = '0';
            len += sprintf(out + len, ".0");
        } else {
            len += sprintf(out + len, "%.*s.%s", exp10 + 1, digits, digits + exp10 + 1);
        }
    } else {
        out[len++] = digits[0];
        if (n > 1) len += sprintf(out + len, ".%s", digits + 1);
        len += sprintf(out + len, "e%c%02d", exp10 < 0 ? '-' : '+', abs(exp10));
    }
    out[len] = '\0';
    return len;
}

void tomato_print_f64(double v) {
    char out[96];
    format_f64(v, out);
    fputs(out, stdout);
}

static void bad_input(int position, const char *what, const char *text) {
    char msg[256];
    snprintf(msg, sizeof msg, "input %d must be %s, found '%s'", position, what, text);
    tomato_fail(msg);
}

void tomato_usage(int expected, int got) {
    char msg[128];
    snprintf(msg, sizeof msg, "the entry point takes %d input(s), got %d", expected, got);
    tomato_fail(msg);
}

int64_t tomato_parse_i64(const char *text, int position) {
    char *end;
    errno = 0;
    long long v = strtoll(text, &end, 10);
    if (*text == '\0' || *end != '\0' || errno != 0 || isspace((unsigned char)*text))
        bad_input(position, "a whole number", text);
    return v;
}

uint64_t tomato_parse_u64(const char *text, int position) {
    char *end;
    errno = 0;
    if (*text == '-' || *text == '+' || isspace((unsigned char)*text)) bad_input(position, "a whole number", text);
    unsigned long long v = strtoull(text, &end, 10);
    if (*text == '\0' || *end != '\0' || errno != 0) bad_input(position, "a whole number", text);
    return v;
}

double tomato_parse_f64(const char *text, int position) {
    char *end;
    double v = strtod(text, &end);
    if (*text == '\0' || *end != '\0' || isnan(v) || isinf(v)) bad_input(position, "a finite number", text);
    return v;
}

int tomato_parse_bool(const char *text, int position) {
    if (!strcmp(text, "true") || !strcmp(text, "True")) return 1;
    if (!strcmp(text, "false") || !strcmp(text, "False")) return 0;
    bad_input(position, "true or false", text);
    return 0;
}

/* x ** y for whole numbers (P57). The status goes in tomato_pow_overflow: 0 fine, 1 the result does not fit 64 bits,
   2 the exponent is negative. */
int tomato_pow_overflow;
int64_t tomato_ipow(int64_t x, int64_t y) {
    tomato_pow_overflow = 0;
    if (y < 0) { tomato_pow_overflow = 2; return 0; }
    int64_t r = 1;
    while (y > 0) {
        if (y & 1) { if (__builtin_mul_overflow(r, x, &r)) { tomato_pow_overflow = 1; return 0; } }
        y >>= 1;
        if (y > 0 && __builtin_mul_overflow(x, x, &x)) { tomato_pow_overflow = 1; return 0; }
    }
    return r;
}

/* Checks that a parsed integer fits an N-bit type (N < 64) before the generated code narrows it. */
void tomato_fit_signed(int64_t v, int bits, int position) {
    if (v < -((int64_t)1 << (bits - 1)) || v >= ((int64_t)1 << (bits - 1))) {
        char msg[128];
        snprintf(msg, sizeof msg, "input %d (%lld) does not fit int[length=%d]", position, (long long)v, bits);
        tomato_fail(msg);
    }
}

void tomato_fit_unsigned(uint64_t v, int bits, int position) {
    if (v >= ((uint64_t)1 << bits)) {
        char msg[128];
        snprintf(msg, sizeof msg, "input %d (%llu) does not fit uint[length=%d]", position, (unsigned long long)v, bits);
        tomato_fail(msg);
    }
}


/* ---- allocation and reference counting ---- */
void *tomato_alloc(int64_t size, int64_t type) {
    Hdr *h = calloc(1, (size_t)size);
    if (!h) tomato_fail("out of memory");
    h->rc = 1;
    h->type = type;
    live_objects++;
    return h;
}

void tomato_retain(void *p) {
    if (p && ((Hdr *)p)->rc > 0) ((Hdr *)p)->rc++;   /* an immortal object (rc < 0) is never counted */
}

void tomato_release(void *p) {
    if (!p) return;
    Hdr *h = p;
    if (h->rc <= 0) return;                 /* immortal (negative) or already dead */
    if (--h->rc == 0) destroy_object(h);
    else possible_root(h);                  /* still referenced: it might be the last outside reference of a cycle */
}

/* Debug mode: objects still alive at exit were never released, usually a reference cycle (D29c). */
#ifndef TOMATO_WASM
extern int32_t tomato_exc_seen;   /* set when any error was raised during the run */
extern const char *tomato_class_names[];
#endif

void tomato_collect_cycles(void);

void tomato_leak_check(void) {
    tomato_collect_cycles();     /* cycles are freed automatically (D29d), so only true leaks are left to report */
    /* After an error was raised, temporaries held in the middle of an expression can be dropped without being
     * released, so the check would report false leaks: it stays quiet then. */
    if (live_objects != 0 && !tomato_exc_seen) {
        fflush(stdout);
        fprintf(stderr, "warning: %lld object(s) were never freed (a reference cycle or a missing release)\n",
                (long long)live_objects);
    }
}

/* ---- strings: {header, byte length, character length, UTF-8 bytes}; type code 1 ---- */
typedef struct { Hdr h; int64_t bytes; int64_t chars; char data[]; } Str;

static int64_t count_chars(const char *s, int64_t n) {
    int64_t k = 0;
    for (int64_t i = 0; i < n; i++) if (((unsigned char)s[i] & 0xC0) != 0x80) k++;
    return k;
}

static Str *str_new(const char *bytes, int64_t n) {
    Str *s = tomato_alloc((int64_t)sizeof(Str) + n + 1, 1);
    memcpy(s->data, bytes, (size_t)n);
    s->bytes = n;
    s->chars = count_chars(bytes, n);
    return s;
}

void *tomato_str_from_cstr(const char *c) { return str_new(c, (int64_t)strlen(c)); }

void *tomato_str_concat(void *a, void *b) {
    Str *x = a, *y = b;
    Str *s = tomato_alloc((int64_t)sizeof(Str) + x->bytes + y->bytes + 1, 1);
    memcpy(s->data, x->data, (size_t)x->bytes);
    memcpy(s->data + x->bytes, y->data, (size_t)y->bytes);
    s->bytes = x->bytes + y->bytes;
    s->chars = x->chars + y->chars;
    return s;
}

int64_t tomato_str_len(void *s) { return ((Str *)s)->chars; }

/* Compares by bytes, which for UTF-8 is the same as comparing code points (D17b). Returns <0, 0 or >0. */
int tomato_str_cmp(void *a, void *b) {
    Str *x = a, *y = b;
    int64_t n = x->bytes < y->bytes ? x->bytes : y->bytes;
    int r = memcmp(x->data, y->data, (size_t)n);
    if (r) return r;
    return x->bytes < y->bytes ? -1 : x->bytes > y->bytes ? 1 : 0;
}

/* The byte offset of character number i (0 <= i <= chars). The scan is linear; a chunked index is later work (D17c). */
static int64_t char_offset(Str *s, int64_t i) {
    int64_t seen = 0;
    for (int64_t k = 0; k < s->bytes; k++) {
        if (((unsigned char)s->data[k] & 0xC0) != 0x80) {
            if (seen == i) return k;
            seen++;
        }
    }
    return s->bytes;
}

void *tomato_str_index(void *a, int64_t i) {
    Str *s = a;
    if (i < 0) i += s->chars;       /* a negative position counts from the end */
    if (i < 0 || i >= s->chars) return NULL;      /* the compiled code raises the error */
    int64_t from = char_offset(s, i), to = char_offset(s, i + 1);
    return str_new(s->data + from, to - from);
}

void *tomato_str_slice(void *a, int64_t lo, int64_t hi) {
    Str *s = a;
    if (lo < 0 || lo > hi || hi > s->chars) return NULL;
    int64_t from = char_offset(s, lo), to = char_offset(s, hi);
    return str_new(s->data + from, to - from);
}

/* ---- slices with Python's rules: negative positions count from the end, out-of-range ends are clamped, a step may be
 * negative. flags: 1 the start was written, 2 the stop was written, 4 the step was written. ---- */
static int64_t slice_plan(int64_t len, int64_t lo, int64_t hi, int64_t step, int flags, int64_t *start) {
    if (!(flags & 4)) step = 1;
    if (step == 0) return -1;      /* the compiled code raises the error */
    int64_t lower = step < 0 ? -1 : 0, upper = step < 0 ? len - 1 : len;
    int64_t a, b;
    if (!(flags & 1)) a = step < 0 ? upper : lower;
    else { a = lo; if (a < 0) { a += len; if (a < lower) a = lower; } else if (a > upper) a = upper; }
    if (!(flags & 2)) b = step < 0 ? lower : upper;
    else { b = hi; if (b < 0) { b += len; if (b < lower) b = lower; } else if (b > upper) b = upper; }
    *start = a;
    if (step < 0) return b < a ? (a - b - 1) / (-step) + 1 : 0;
    return a < b ? (b - a - 1) / step + 1 : 0;
}

void *tomato_str_slice3(void *a, int64_t lo, int64_t hi, int64_t step, int flags) {
    Str *s = a;
    int64_t start, n = slice_plan(s->chars, lo, hi, step, flags, &start);
    if (n < 0) return NULL;
    if (!(flags & 4)) step = 1;
    if (step == 1) {
        if (n == 0) return str_new("", 0);
        int64_t from = char_offset(s, start), to = char_offset(s, start + n);
        return str_new(s->data + from, to - from);
    }
    char *out = malloc((size_t)s->bytes + 1);
    if (!out) tomato_fail("out of memory");
    int64_t at = 0;
    for (int64_t k = 0; k < n; k++) {
        int64_t i = start + k * step;
        int64_t from = char_offset(s, i), to = char_offset(s, i + 1);
        memcpy(out + at, s->data + from, (size_t)(to - from));
        at += to - from;
    }
    void *r = str_new(out, at);
    free(out);
    return r;
}

/* ---- text searching and splitting (bootstrap, D38a) ---- */
void *tomato_list_new(int64_t type);
void *tomato_list_push(void *l, int64_t elem_size);
static int64_t byte_to_char(Str *s, int64_t byte) {
    int64_t seen = 0;
    for (int64_t k = 0; k < byte; k++)
        if (((unsigned char)s->data[k] & 0xC0) != 0x80) seen++;
    return seen;
}

static int64_t find_bytes(Str *h, Str *n, int64_t from) {
    if (n->bytes == 0) return from <= h->bytes ? from : -1;
    for (int64_t i = from; i + n->bytes <= h->bytes; i++)
        if (memcmp(h->data + i, n->data, (size_t)n->bytes) == 0) return i;
    return -1;
}

/* The character index of the first match, or -1. */
int64_t tomato_str_find(void *hay, void *needle) {
    int64_t at = find_bytes(hay, needle, 0);
    return at < 0 ? -1 : byte_to_char(hay, at);
}

int tomato_str_startswith(void *hay, void *p) {
    Str *h = hay, *x = p;
    return x->bytes <= h->bytes && memcmp(h->data, x->data, (size_t)x->bytes) == 0;
}

int tomato_str_endswith(void *hay, void *p) {
    Str *h = hay, *x = p;
    return x->bytes <= h->bytes && memcmp(h->data + h->bytes - x->bytes, x->data, (size_t)x->bytes) == 0;
}

/* Every non-overlapping `a` replaced by `b`; the compiler rejects an empty `a`. */
void *tomato_str_replace(void *src, void *a, void *b) {
    Str *s = src, *x = a, *y = b;
    int64_t cap = s->bytes + 1, len = 0, at = 0;
    char *out = malloc((size_t)cap);
    if (!out) tomato_fail("out of memory");
    while (at <= s->bytes) {
        int64_t hit = find_bytes(s, x, at);
        int64_t upto = hit < 0 ? s->bytes : hit;
        int64_t need = len + (upto - at) + (hit < 0 ? 0 : y->bytes) + 1;
        if (need > cap) { cap = need * 2; out = realloc(out, (size_t)cap); if (!out) tomato_fail("out of memory"); }
        memcpy(out + len, s->data + at, (size_t)(upto - at));
        len += upto - at;
        if (hit < 0) break;
        memcpy(out + len, y->data, (size_t)y->bytes);
        len += y->bytes;
        at = hit + x->bytes;
    }
    void *r = str_new(out, len);
    free(out);
    return r;
}

/* A new list of the pieces between each `sep`; the compiler rejects an empty `sep`. */
void *tomato_str_split(void *src, void *sep, int64_t list_type, int64_t elem_size) {
    Str *s = src, *x = sep;
    void *l = tomato_list_new(list_type);
    int64_t at = 0;
    for (;;) {
        int64_t hit = find_bytes(s, x, at);
        int64_t upto = hit < 0 ? s->bytes : hit;
        void *piece = str_new(s->data + at, upto - at);
        void **slot = tomato_list_push(l, elem_size);
        *slot = piece;
        if (hit < 0) break;
        at = hit + x->bytes;
    }
    return l;
}

/* ASCII-only case changes and trimming (bootstrap, D38a); bytes of other characters are kept as they are. */
void *tomato_str_upper(void *src) {
    Str *s = src;
    char *t = malloc((size_t)s->bytes + 1);
    if (!t) tomato_fail("out of memory");
    for (int64_t i = 0; i < s->bytes; i++) t[i] = (s->data[i] >= 'a' && s->data[i] <= 'z') ? s->data[i] - 32 : s->data[i];
    void *r = str_new(t, s->bytes);
    free(t);
    return r;
}

void *tomato_str_lower(void *src) {
    Str *s = src;
    char *t = malloc((size_t)s->bytes + 1);
    if (!t) tomato_fail("out of memory");
    for (int64_t i = 0; i < s->bytes; i++) t[i] = (s->data[i] >= 'A' && s->data[i] <= 'Z') ? s->data[i] + 32 : s->data[i];
    void *r = str_new(t, s->bytes);
    free(t);
    return r;
}

void *tomato_str_strip(void *src) {
    Str *s = src;
    int64_t a = 0, b = s->bytes;
    while (a < b && isspace((unsigned char)s->data[a])) a++;
    while (b > a && isspace((unsigned char)s->data[b - 1])) b--;
    return str_new(s->data + a, b - a);
}

/* ---- files (bootstrap, D38a): a FILE* the program opens and closes itself ---- */
void *tomato_file_open(void *path, void *mode) {
    return fopen(((Str *)path)->data, ((Str *)mode)->data);
}

void *tomato_file_read(void *f) {
    char buf[4096];
    int64_t cap = 4096, len = 0;
    char *out = malloc((size_t)cap);
    size_t got;
    if (!out) tomato_fail("out of memory");
    while ((got = fread(buf, 1, sizeof buf, f)) > 0) {
        if (len + (int64_t)got > cap) { cap = (len + (int64_t)got) * 2; out = realloc(out, (size_t)cap); if (!out) tomato_fail("out of memory"); }
        memcpy(out + len, buf, got);
        len += (int64_t)got;
    }
    void *r = str_new(out, len);
    free(out);
    return r;
}

void tomato_file_write(void *f, void *s) { fwrite(((Str *)s)->data, 1, (size_t)((Str *)s)->bytes, f); }
void tomato_file_close(void *f) { fclose(f); }

void tomato_print_strobj(void *s) { fwrite(((Str *)s)->data, 1, (size_t)((Str *)s)->bytes, stdout); }

