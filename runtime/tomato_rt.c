int64_t tomato_http_error_kind(int64_t id) { HttpReq *r = http_get(id); return r ? r->kind : HK_OTHER; }
void *tomato_http_error_text(int64_t id) { HttpReq *r = http_get(id); return tomato_str_from_cstr(r && r->kind && r->err ? r->err : ""); }
