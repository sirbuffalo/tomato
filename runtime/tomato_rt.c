static int32_t case_map(const int32_t (*rows)[4], int n, int32_t cp) {
    int lo = 0, hi = n - 1;
    while (lo <= hi) {
        int mid = (lo + hi) / 2;
        if (cp < rows[mid][0]) hi = mid - 1;
        else if (cp > rows[mid][1]) lo = mid + 1;
        else return (cp - rows[mid][0]) % rows[mid][3] == 0 ? cp + rows[mid][2] : cp;
    }
    return cp;
}

static void *change_case(void *src, int upper) {
    Str *s = src;
    char *t = malloc((size_t)s->bytes * 3 + 1);   /* a mapped letter never grows by more than 2 bytes */
    if (!t) out_of_memory();
    int64_t i = 0, o = 0;
    const unsigned char *p = (const unsigned char *)s->data;
    while (i < s->bytes) {
        unsigned char c = p[i];
        if (c < 0x80) {
            t[o++] = upper ? ((c >= 'a' && c <= 'z') ? c - 32 : c) : ((c >= 'A' && c <= 'Z') ? c + 32 : c);
            i++;
            continue;
        }
        int len = c >= 0xF0 ? 4 : c >= 0xE0 ? 3 : c >= 0xC0 ? 2 : 1;
        int32_t cp = len == 4 ? c & 7 : len == 3 ? c & 15 : len == 2 ? c & 31 : -1;
        if (len == 1 || i + len > s->bytes) { t[o++] = (char)c; i++; continue; }   /* not UTF-8: kept as it is */
        int good = 1;
        for (int k = 1; k < len; k++) {
            if ((p[i + k] & 0xC0) != 0x80) good = 0;
            cp = (cp << 6) | (p[i + k] & 0x3F);
        }
        if (!good) { t[o++] = (char)c; i++; continue; }
        int32_t m = upper ? case_map(case_upper_rows, (int)(sizeof case_upper_rows / sizeof case_upper_rows[0]), cp)
                          : case_map(case_lower_rows, (int)(sizeof case_lower_rows / sizeof case_lower_rows[0]), cp);
        if (m < 0x80) t[o++] = (char)m;
        else if (m < 0x800) { t[o++] = (char)(0xC0 | (m >> 6)); t[o++] = (char)(0x80 | (m & 0x3F)); }
        else if (m < 0x10000) { t[o++] = (char)(0xE0 | (m >> 12)); t[o++] = (char)(0x80 | ((m >> 6) & 0x3F)); t[o++] = (char)(0x80 | (m & 0x3F)); }
        else { t[o++] = (char)(0xF0 | (m >> 18)); t[o++] = (char)(0x80 | ((m >> 12) & 0x3F)); t[o++] = (char)(0x80 | ((m >> 6) & 0x3F)); t[o++] = (char)(0x80 | (m & 0x3F)); }
        i += len;
    }
    void *r = str_new(t, o);
    free(t);
    return r;
}

void *tomato_str_upper(void *src) { return change_case(src, 1); }
void *tomato_str_lower(void *src) { return change_case(src, 0); }

