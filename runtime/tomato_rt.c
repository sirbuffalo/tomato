static int in_rows(const int32_t (*rows)[2], int n, int32_t cp) {
    int lo = 0, hi = n - 1;
    while (lo <= hi) {
        int mid = (lo + hi) / 2;
        if (cp < rows[mid][0]) hi = mid - 1;
        else if (cp > rows[mid][1]) lo = mid + 1;
        else return 1;
    }
    return 0;
}

/* 1 when the text is not empty and every character is a letter (digits = 0) or a digit (digits = 1); bytes that are not UTF-8 are neither */
static int32_t all_class(void *src, int digits) {
    Str *s = src;
    const unsigned char *p = (const unsigned char *)s->data;
    if (s->bytes == 0) return 0;
    int64_t i = 0;
    while (i < s->bytes) {
        unsigned char c = p[i];
        if (c < 0x80) {
            int ok = digits ? (c >= '0' && c <= '9') : ((c | 32) >= 'a' && (c | 32) <= 'z');
            if (!ok) return 0;
            i++;
            continue;
        }
        int len = c >= 0xF0 ? 4 : c >= 0xE0 ? 3 : c >= 0xC0 ? 2 : 1;
        if (len == 1 || i + len > s->bytes) return 0;
        int32_t cp = len == 4 ? c & 7 : len == 3 ? c & 15 : c & 31;
        for (int k = 1; k < len; k++) {
            if ((p[i + k] & 0xC0) != 0x80) return 0;
            cp = (cp << 6) | (p[i + k] & 0x3F);
        }
        int ok = digits ? in_rows(ctype_digit_rows, (int)(sizeof ctype_digit_rows / sizeof ctype_digit_rows[0]), cp)
                        : in_rows(ctype_alpha_rows, (int)(sizeof ctype_alpha_rows / sizeof ctype_alpha_rows[0]), cp);
        if (!ok) return 0;
        i += len;
    }
    return 1;
}

int32_t tomato_str_isalpha(void *src) { return all_class(src, 0); }
